/**
  * @brief  Send a single HID keyboard keypress (press + release) report.
  * @param  keycode: USB HID keyboard usage ID of the key to send.
  * @retval None
  */
static void SendKeyPress(uint8_t keycode)
{
  uint8_t report[8] = {0};

  /* Byte 0: modifier keys, Byte 1: reserved, Bytes 2-7: up to 6 keycodes */
  report[2] = keycode;
  USBD_HID_SendReport(&hUsbDeviceFS, report, sizeof(report));

  HAL_Delay(10);

  /* Send an all-zero report to release the key */
  memset(report, 0, sizeof(report));
  USBD_HID_SendReport(&hUsbDeviceFS, report, sizeof(report));
}

